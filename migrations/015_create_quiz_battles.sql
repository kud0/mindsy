-- ===== quiz_battles policies =====

DROP POLICY IF EXISTS "Users can view their battles" ON quiz_battles;
CREATE POLICY "Users can view their battles"
  ON quiz_battles
  FOR SELECT
  USING (
    auth.uid() = created_by
    OR auth.uid() = opponent_id
  );

DROP POLICY IF EXISTS "Users can create battles" ON quiz_battles;
CREATE POLICY "Users can create battles"
  ON quiz_battles
  FOR INSERT
  WITH CHECK (auth.uid() = created_by);

DROP POLICY IF EXISTS "Users can update their battles" ON quiz_battles;
CREATE POLICY "Users can update their battles"
  ON quiz_battles
  FOR UPDATE
  USING (
    auth.uid() = created_by
    OR auth.uid() = opponent_id
  )
  WITH CHECK (
    auth.uid() = created_by
    OR auth.uid() = opponent_id
  );

DROP POLICY IF EXISTS "Users can delete pending battles" ON quiz_battles;
CREATE POLICY "Users can delete pending battles"
  ON quiz_battles
  FOR DELETE
  USING (
    auth.uid() = created_by
    AND status = 'pending'
  );

