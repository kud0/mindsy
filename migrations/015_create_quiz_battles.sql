-- ===== Trigger 1: Notify battle challenge =====
-- Sends notification when a user is challenged to a battle

CREATE OR REPLACE FUNCTION notify_battle_challenge()
RETURNS TRIGGER AS $$
DECLARE
  challenger_name TEXT;
BEGIN
  -- Only notify when battle is first created with pending status
  IF NEW.status = 'pending' THEN
    -- Get challenger's name
    SELECT COALESCE(
      raw_user_meta_data->>'full_name',
      raw_user_meta_data->>'name',
      email
    ) INTO challenger_name
    FROM auth.users
    WHERE id = NEW.created_by;

    -- Create notification for opponent
    PERFORM create_notification(
      NEW.opponent_id,
      'battle_challenge',
      'Quiz Battle Challenge!',
      challenger_name || ' challenged you to a quiz battle on "' || NEW.source_folder_name || '"',
      NEW.id,
      NEW.created_by,
      '/dashboard/social/battles/' || NEW.id,
      jsonb_build_object(
        'battle_id', NEW.id,
        'folder_name', NEW.source_folder_name,
        'rounds', NEW.rounds_count,
        'questions_per_round', NEW.questions_per_round
      )
    );
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS notify_battle_challenge_trigger ON quiz_battles;

CREATE TRIGGER notify_battle_challenge_trigger
  AFTER INSERT ON quiz_battles
  FOR EACH ROW
  EXECUTE FUNCTION notify_battle_challenge();

-- ===== Trigger 2: Notify battle result =====
-- Sends notification when battle is completed with results

CREATE OR REPLACE FUNCTION notify_battle_result()
RETURNS TRIGGER AS $$
DECLARE
  challenger_name TEXT;
  opponent_name TEXT;
  winner_name TEXT;
  result_message TEXT;
BEGIN
  -- Only notify when status changes to completed
  IF OLD.status != 'completed' AND NEW.status = 'completed' THEN
    -- Get participant names
    SELECT COALESCE(
      raw_user_meta_data->>'full_name',
      raw_user_meta_data->>'name',
      email
    ) INTO challenger_name
    FROM auth.users
    WHERE id = NEW.created_by;

    SELECT COALESCE(
      raw_user_meta_data->>'full_name',
      raw_user_meta_data->>'name',
      email
    ) INTO opponent_name
    FROM auth.users
    WHERE id = NEW.opponent_id;

    -- Determine result message
    IF NEW.winner_id IS NULL THEN
      result_message := 'It''s a draw! Great effort from both of you.';
    ELSIF NEW.winner_id = NEW.created_by THEN
      winner_name := challenger_name;
      result_message := winner_name || ' won the battle!';
    ELSE
      winner_name := opponent_name;
      result_message := winner_name || ' won the battle!';
    END IF;

    -- Notify challenger
    PERFORM create_notification(
      NEW.created_by,
      'battle_result',
      'Battle Completed!',
      result_message,
      NEW.id,
      NEW.opponent_id,
      '/dashboard/social/battles/' || NEW.id || '/results',
      jsonb_build_object(
        'battle_id', NEW.id,
        'winner_id', NEW.winner_id,
        'is_draw', NEW.winner_id IS NULL,
        'is_winner', NEW.winner_id = NEW.created_by
      )
    );

    -- Notify opponent
    PERFORM create_notification(
      NEW.opponent_id,
      'battle_result',
      'Battle Completed!',
      result_message,
      NEW.id,
      NEW.created_by,
      '/dashboard/social/battles/' || NEW.id || '/results',
      jsonb_build_object(
        'battle_id', NEW.id,
        'winner_id', NEW.winner_id,
        'is_draw', NEW.winner_id IS NULL,
        'is_winner', NEW.winner_id = NEW.opponent_id
      )
    );
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS notify_battle_result_trigger ON quiz_battles;

CREATE TRIGGER notify_battle_result_trigger
  AFTER UPDATE ON quiz_battles
  FOR EACH ROW
  EXECUTE FUNCTION notify_battle_result();

-- ===== Trigger 3: Update battle stats =====
-- Updates aggregated statistics when battle completes

CREATE OR REPLACE FUNCTION update_battle_stats()
RETURNS TRIGGER AS $$
DECLARE
  challenger_score INTEGER;
  opponent_score INTEGER;
  participant_record RECORD;
  round_record RECORD;
  question JSONB;
  user_answer INTEGER;
  correct_answer INTEGER;
  topic TEXT;
BEGIN
  -- Only update stats when status changes to completed
  IF OLD.status != 'completed' AND NEW.status = 'completed' THEN

    -- Calculate total scores for both participants
    SELECT COALESCE(SUM(score), 0) INTO challenger_score
    FROM battle_participants
    WHERE battle_id = NEW.id AND user_id = NEW.created_by;

    SELECT COALESCE(SUM(score), 0) INTO opponent_score
    FROM battle_participants
    WHERE battle_id = NEW.id AND user_id = NEW.opponent_id;

    -- Update stats for challenger
    INSERT INTO battle_stats (user_id, total_battles, wins, losses, draws, last_battle_at)
    VALUES (
      NEW.created_by,
      1,
      CASE WHEN NEW.winner_id = NEW.created_by THEN 1 ELSE 0 END,
      CASE WHEN NEW.winner_id = NEW.opponent_id THEN 1 ELSE 0 END,
      CASE WHEN NEW.winner_id IS NULL THEN 1 ELSE 0 END,
      NEW.completed_at
    )
    ON CONFLICT (user_id) DO UPDATE SET
      total_battles = battle_stats.total_battles + 1,
      wins = battle_stats.wins + CASE WHEN NEW.winner_id = NEW.created_by THEN 1 ELSE 0 END,
      losses = battle_stats.losses + CASE WHEN NEW.winner_id = NEW.opponent_id THEN 1 ELSE 0 END,
      draws = battle_stats.draws + CASE WHEN NEW.winner_id IS NULL THEN 1 ELSE 0 END,
      last_battle_at = NEW.completed_at,
      updated_at = NOW();

    -- Update stats for opponent
    INSERT INTO battle_stats (user_id, total_battles, wins, losses, draws, last_battle_at)
    VALUES (
      NEW.opponent_id,
      1,
      CASE WHEN NEW.winner_id = NEW.opponent_id THEN 1 ELSE 0 END,
      CASE WHEN NEW.winner_id = NEW.created_by THEN 1 ELSE 0 END,
      CASE WHEN NEW.winner_id IS NULL THEN 1 ELSE 0 END,
      NEW.completed_at
    )
    ON CONFLICT (user_id) DO UPDATE SET
      total_battles = battle_stats.total_battles + 1,
      wins = battle_stats.wins + CASE WHEN NEW.winner_id = NEW.opponent_id THEN 1 ELSE 0 END,
      losses = battle_stats.losses + CASE WHEN NEW.winner_id = NEW.created_by THEN 1 ELSE 0 END,
      draws = battle_stats.draws + CASE WHEN NEW.winner_id IS NULL THEN 1 ELSE 0 END,
      last_battle_at = NEW.completed_at,
      updated_at = NOW();

    -- Analyze topics for both participants
    FOR participant_record IN
      SELECT user_id, battle_id, round_number, answers
      FROM battle_participants
      WHERE battle_id = NEW.id
    LOOP
      -- Get questions for this round
      FOR round_record IN
        SELECT questions
        FROM battle_rounds
        WHERE battle_id = participant_record.battle_id
          AND round_number = participant_record.round_number
      LOOP
        -- Analyze each question
        FOR question IN SELECT * FROM jsonb_array_elements(round_record.questions)
        LOOP
          -- Extract user's answer and correct answer
          user_answer := (participant_record.answers->(question->>'id'))::INTEGER;
          correct_answer := (question->>'correctAnswer')::INTEGER;
          topic := question->>'topic';

          -- Skip if no topic
          CONTINUE WHEN topic IS NULL OR topic = '';

          -- Update weak/strong topics
          IF user_answer = correct_answer THEN
            -- Increment strong topic count
            UPDATE battle_stats
            SET strong_topics = jsonb_set(
              strong_topics,
              ARRAY[topic],
              to_jsonb(COALESCE((strong_topics->>topic)::INTEGER, 0) + 1)
            ),
            updated_at = NOW()
            WHERE user_id = participant_record.user_id;
          ELSE
            -- Increment weak topic count
            UPDATE battle_stats
            SET weak_topics = jsonb_set(
              weak_topics,
              ARRAY[topic],
              to_jsonb(COALESCE((weak_topics->>topic)::INTEGER, 0) + 1)
            ),
            updated_at = NOW()
            WHERE user_id = participant_record.user_id;
          END IF;
        END LOOP;
      END LOOP;
    END LOOP;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS update_battle_stats_trigger ON quiz_battles;

CREATE TRIGGER update_battle_stats_trigger
  AFTER UPDATE ON quiz_battles
  FOR EACH ROW
  EXECUTE FUNCTION update_battle_stats();

