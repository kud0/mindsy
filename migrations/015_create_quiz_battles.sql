-- Create quiz battle system for friend-to-friend learning competitions
-- Tables: quiz_battles, battle_rounds, battle_participants, battle_stats
-- Includes RLS policies, indexes, triggers, and notifications

-- ============================================================================
-- TABLE: quiz_battles
-- Main battle entity tracking challenges between friends
-- ============================================================================

CREATE TABLE IF NOT EXISTS quiz_battles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Participants
  created_by UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  opponent_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,

  -- Battle configuration
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'completed', 'cancelled')),
  source_folder_id UUID REFERENCES user_folders(id) ON DELETE SET NULL,
  source_folder_name TEXT NOT NULL,
  rounds_count INTEGER NOT NULL DEFAULT 3 CHECK (rounds_count > 0 AND rounds_count <= 5),
  questions_per_round INTEGER NOT NULL DEFAULT 5 CHECK (questions_per_round > 0 AND questions_per_round <= 20),

  -- Results
  winner_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,

  -- Timestamps
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,

  -- Constraints
  CONSTRAINT valid_participants CHECK (created_by != opponent_id),
  CONSTRAINT valid_completion CHECK (
    (status = 'completed' AND completed_at IS NOT NULL) OR
    (status != 'completed' AND completed_at IS NULL)
  ),
  CONSTRAINT valid_winner CHECK (
    winner_id IS NULL OR winner_id IN (created_by, opponent_id)
  )
);

-- Indexes for fast lookups
CREATE INDEX IF NOT EXISTS idx_quiz_battles_created_by ON quiz_battles(created_by, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_quiz_battles_opponent ON quiz_battles(opponent_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_quiz_battles_status ON quiz_battles(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_quiz_battles_folder ON quiz_battles(source_folder_id);

-- Comments
COMMENT ON TABLE quiz_battles IS 'Friend-to-friend quiz battles for learning competition';
COMMENT ON COLUMN quiz_battles.status IS 'pending = awaiting acceptance, active = in progress, completed = finished, cancelled = rejected';
COMMENT ON COLUMN quiz_battles.source_folder_id IS 'Challenger''s folder containing the quiz content';
COMMENT ON COLUMN quiz_battles.winner_id IS 'NULL = draw, otherwise user who won';

-- ============================================================================
-- TABLE: battle_rounds
-- Individual rounds within a battle, contains questions
-- ============================================================================

CREATE TABLE IF NOT EXISTS battle_rounds (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Parent battle
  battle_id UUID NOT NULL REFERENCES quiz_battles(id) ON DELETE CASCADE,

  -- Round info
  round_number INTEGER NOT NULL CHECK (round_number > 0),

  -- Questions for this round (generated by AI)
  -- Format: [{id, question, options: [string], correctAnswer: number, topic: string}]
  questions JSONB NOT NULL,

  -- Timestamps
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,

  -- Constraints
  CONSTRAINT unique_battle_round UNIQUE (battle_id, round_number),
  CONSTRAINT valid_questions CHECK (jsonb_array_length(questions) > 0)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_battle_rounds_battle ON battle_rounds(battle_id, round_number);
CREATE INDEX IF NOT EXISTS idx_battle_rounds_started ON battle_rounds(started_at DESC);

-- Comments
COMMENT ON TABLE battle_rounds IS 'Individual rounds containing AI-generated questions';
COMMENT ON COLUMN battle_rounds.questions IS 'JSONB array of question objects with answers and topics';

-- ============================================================================
-- TABLE: battle_participants
-- Tracks each participant's answers and scores per round
-- ============================================================================

CREATE TABLE IF NOT EXISTS battle_participants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- References
  battle_id UUID NOT NULL REFERENCES quiz_battles(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  round_number INTEGER NOT NULL CHECK (round_number > 0),

  -- User's answers for this round
  -- Format: {question_id: selected_answer_index}
  answers JSONB NOT NULL DEFAULT '{}'::jsonb,

  -- Performance metrics
  score INTEGER NOT NULL DEFAULT 0 CHECK (score >= 0),
  time_taken INTEGER NOT NULL CHECK (time_taken >= 0), -- seconds

  -- Timestamp
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Constraints
  CONSTRAINT unique_participant_round UNIQUE (battle_id, user_id, round_number)
  -- Note: Participant validation is handled by RLS policies and API layer
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_battle_participants_battle_user ON battle_participants(battle_id, user_id);
CREATE INDEX IF NOT EXISTS idx_battle_participants_user ON battle_participants(user_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_battle_participants_round ON battle_participants(battle_id, round_number);

-- Comments
COMMENT ON TABLE battle_participants IS 'User answers and scores for each round';
COMMENT ON COLUMN battle_participants.answers IS 'JSONB object mapping question_id to selected answer index';
COMMENT ON COLUMN battle_participants.time_taken IS 'Time taken to complete round in seconds';

-- ============================================================================
-- TABLE: battle_stats
-- Aggregated statistics per user for tracking progress and weak/strong topics
-- ============================================================================

CREATE TABLE IF NOT EXISTS battle_stats (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,

  -- Overall stats
  total_battles INTEGER NOT NULL DEFAULT 0 CHECK (total_battles >= 0),
  wins INTEGER NOT NULL DEFAULT 0 CHECK (wins >= 0),
  losses INTEGER NOT NULL DEFAULT 0 CHECK (losses >= 0),
  draws INTEGER NOT NULL DEFAULT 0 CHECK (draws >= 0),

  -- Topic analysis (learning insights)
  -- Format: {topic_name: count}
  weak_topics JSONB NOT NULL DEFAULT '{}'::jsonb,
  strong_topics JSONB NOT NULL DEFAULT '{}'::jsonb,

  -- Timestamps
  last_battle_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Constraints
  CONSTRAINT valid_battle_counts CHECK (total_battles = wins + losses + draws)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_battle_stats_total ON battle_stats(total_battles DESC);
CREATE INDEX IF NOT EXISTS idx_battle_stats_wins ON battle_stats(wins DESC);
CREATE INDEX IF NOT EXISTS idx_battle_stats_last_battle ON battle_stats(last_battle_at DESC);

-- Comments
COMMENT ON TABLE battle_stats IS 'Aggregated battle statistics and learning insights per user';
COMMENT ON COLUMN battle_stats.weak_topics IS 'JSONB object: {topic: wrong_answer_count} for learning recommendations';
COMMENT ON COLUMN battle_stats.strong_topics IS 'JSONB object: {topic: correct_answer_count} for confidence tracking';

